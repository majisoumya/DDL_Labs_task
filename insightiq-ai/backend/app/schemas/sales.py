"""Pydantic Schemas for Sales and Revenue Endpoints."""

from __future__ import annotations

from decimal import Decimal
from typing import List, Optional
from pydantic import BaseModel, Field


class SalesMetricsResponse(BaseModel):
    """Core sales summary KPIs."""
    total_revenue: Decimal = Field(..., description="Gross revenue from eligible orders")
    total_orders: int = Field(..., description="Count of distinct eligible orders")
    aov: Decimal = Field(..., description="Average Order Value (Revenue / Orders)")


class MonthlyRevenueItem(BaseModel):
    """Monthly revenue aggregation item."""
    month: str = Field(..., description="Fiscal month in YYYY-MM format")
    revenue: Decimal = Field(..., description="Total monthly revenue")
    order_count: int = Field(..., description="Total orders placed in the month")
    units_sold: int = Field(..., description="Total product units sold in the month")


class CategoryRevenueItem(BaseModel):
    """Category breakdown item."""
    category: str = Field(..., description="Product category name")
    revenue: Decimal = Field(..., description="Gross revenue generated by category")
    percentage: float = Field(..., description="Percentage contribution to total revenue")
    order_count: int = Field(..., description="Distinct orders containing this category")
    units_sold: int = Field(..., description="Total units sold in this category")


class ProductRevenueItem(BaseModel):
    """Product revenue item."""
    product_id: int
    product_name: str
    category: str
    revenue: Decimal
    units_sold: int


class PeriodMetrics(BaseModel):
    """Metrics for an individual time window."""
    start: str
    end: str
    revenue: Decimal
    orders: int
    aov: Decimal


class SalesGrowthResponse(BaseModel):
    """Period-over-period comparison response."""
    current_period: PeriodMetrics
    previous_period: PeriodMetrics
    revenue_growth_pct: Optional[float] = Field(None, description="Percentage change in revenue")
    orders_growth_pct: Optional[float] = Field(None, description="Percentage change in order volume")
    aov_growth_pct: Optional[float] = Field(None, description="Percentage change in Average Order Value")
