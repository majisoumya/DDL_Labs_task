"""Pydantic Schemas for Product Analytics Endpoints."""

from __future__ import annotations

from decimal import Decimal
from typing import Optional
from pydantic import BaseModel, Field


class ProductSummary(BaseModel):
    """Product performance summary item."""
    product_id: int
    product_name: str
    category: str
    revenue: Decimal = Field(..., description="Gross revenue generated by product")
    units_sold: int = Field(..., description="Total unit volume sold")
    stock: int = Field(..., description="Current catalog inventory stock level")


class ProductDetailResponse(BaseModel):
    """Detailed performance metrics for a single catalog item."""
    product_id: int
    product_name: str
    category: str
    units_sold: int
    revenue: Decimal
    order_count: int
